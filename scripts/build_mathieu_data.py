"""Find coordinate permutations for the seven-point Mathieu stabilizer chain.

The generated arrays supply witnesses to Lean. The search and its assertions
are not used as proof rules.
"""
from itertools import combinations
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
rows = re.findall(r'=>\s*#\[([^\]]+)\]', (root / 'GolayMatrixDistance.lean').read_text(encoding='utf-8'))
assert len(rows) == 12
generators = [(1 << i) | sum(1 << (12+j) for j, bit in enumerate(row.split(',')) if bit.strip() == 'true')
              for i, row in enumerate(rows)]
code = [0]
for g in generators:
    code += [v ^ g for v in code]
points = range(24)
octads = {five: w for w in code if w.bit_count() == 8
          for five in combinations([i for i in points if w >> i & 1], 5)}
assert len(octads) == 42504
base = (0, 1, 2, 3, 4, 13, 5)
standard = octads[base[:5]]
selected = {}
for five in combinations(base, 5):
    selected.setdefault(octads[tuple(sorted(five))], five)
assert len(selected) == 16
five_indices = [tuple(base.index(i) for i in five) for five in selected.values()]

def signatures(octs):
    return [sum((w >> j & 1) << k for k, w in enumerate(octs)) for j in points]

source_signature = signatures(selected)
def find_permutation(image):
    target_signature = signatures([octads[tuple(sorted(image[k] for k in f))] for f in five_indices])
    assert sorted(target_signature) == sorted(source_signature)
    perm = [target_signature.index(t) for t in source_signature]
    pair = [i for i in points if source_signature[i] == source_signature[15]]
    targets = [j for j in points if target_signature[j] == source_signature[15]]
    for a, b in (targets, targets[::-1]):
        perm[pair[0]], perm[pair[1]] = a, b
        if all(code[(v := sum(((w >> perm[j]) & 1) << j for j in points)) & 4095] == v
               for w in generators):
            assert [perm[i] for i in base] == list(image)
            return perm
    raise ValueError(f'No code permutation with base images {image}')

allowed = []
slots, reps, row_messages = [], [], []
for k, pt in enumerate(base):
    images = [j for j in points if j not in base[:k] and
              (k < 5 or (standard >> pt & 1) == (standard >> j & 1))]
    allowed.append(images)
    lookup = [0]*24
    for j in images:
        image = list(base[:k]) + [j]
        while len(image) < 5:
            image.append(next(t for t in points if t not in image))
        block = octads[tuple(sorted(image[:5]))]
        if len(image) < 6:
            image.append(next(t for t in points if block >> t & 1 and t not in image))
        if len(image) < 7:
            image.append(next(t for t in points if not (block >> t & 1)))
        rep = find_permutation(image)
        lookup[j] = len(reps)
        reps.append(rep)
        row_messages.append([sum(((w >> rep[t]) & 1) << t for t in range(12)) for w in generators])
    slots.append(lookup)
assert list(map(len, allowed)) == [24, 23, 22, 21, 20, 3, 16]
extra = (0, 1, 4, 5, 6)
selected[octads[extra]] = extra
assert len(set(signatures(selected))) == 24

def array(xs):
    return '#[' + ', '.join(map(str, xs)) + ']'
def table(name, xs):
    return 'def ' + name + ' : Array (Array Nat) := #[\n  ' + ',\n  '.join(map(array, xs)) + ']\n'

body = '/-! # Finite witnesses for the Golay coordinate permutations\n\nGenerated by `scripts/build_mathieu_data.py`. -/\n\nnamespace MathieuData\n\n'
body += 'def basePoints : Array Nat := ' + array(base) + '\n\n'
body += 'def octadMasks : Array UInt32 := ' + array(selected) + '\n\n'
body += table('anchorPoints', selected.values()) + '\n'
body += table('slots', slots) + '\n' + table('perms', reps) + '\n' + table('messages', row_messages)
body += '\nend MathieuData\n'
path = root / 'MathieuData.lean'
if '--check' in sys.argv:
    assert path.read_text(encoding='utf-8') == body
else:
    path.write_text(body, encoding='utf-8')
print(f'{len(reps)} transversals, {len(selected)} octads. Orbit lengths: {list(map(len, allowed))}')
